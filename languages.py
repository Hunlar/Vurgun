def _format_bot_template(template: str, values: dict) -> str:
    if not values:
        return template
    args = dict(values)
    if "count" in args:
        args.setdefault("n", args["count"])
    if "n" in args:
        args.setdefault("count", args["n"])
    if "rounds" in args:
        args.setdefault("round", args["rounds"])
    try:
        return template.format(**args)
    except (KeyError, ValueError, IndexError):
        return template


def get_text(lang: str, key: str, **values) -> str:
    """Get a bot UI/game string and safely interpolate its named values."""
    language = lang if lang in LANGUAGES else "tr"

    if key.startswith("night_action_"):
        action_key = key.removeprefix("night_action_")
        template = NIGHT_ACTIONS.get(language, NIGHT_ACTIONS["tr"]).get(
            action_key, NIGHT_ACTIONS["tr"].get(action_key, key)
        )
    elif key == "night_action_title":
        title = NIGHT_ACTIONS.get(language, NIGHT_ACTIONS["tr"]).get("title", "🌙")
        template = _BOT_TEXTS["tr"][key].replace("🌙 <b>Gece operasyonu</b>", title)
    elif key == "skip_action":
        template = NIGHT_ACTIONS.get(language, NIGHT_ACTIONS["tr"]).get("skip", "⏭")
    elif key == "help_message":
        template = HELP_TEXTS.get(language, HELP_TEXTS["tr"])
    elif key in TEXTS.get(language, {}):
        template = TEXTS[language][key]
    elif key in _BOT_KEY_ALIASES:
        alias = _BOT_KEY_ALIASES[key]
        if alias in TEXTS.get(language, {}):
            template = TEXTS[language][alias]
        else:
            template = GAME_TEXTS.get(language, GAME_TEXTS["tr"]).get(
                alias, GAME_TEXTS["tr"].get(alias, key)
            )
    elif key in GAME_TEXTS.get(language, {}):
        template = GAME_TEXTS[language][key]
    elif key in _BOT_TEXTS.get(language, {}):
        template = _BOT_TEXTS[language][key]
    else:
        template = _BOT_TEXTS["tr"].get(key, TEXTS["tr"].get(key, key))

    # Some game keys need a bot-specific template because the older game
    # template expects different placeholders.
    if key in ("vote_line", "vote_tie", "player_eliminated", "kamikaze_hit"):
        template = _BOT_TEXTS.get(language, _BOT_TEXTS["tr"]).get(key, _BOT_TEXTS["tr"][key])
    if key == "night_action_title":
        template = template.replace("{action}", str(values.get("action", "")))
        return template
    return _format_bot_template(template, values)


